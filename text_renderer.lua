local function plotPixel(buffer, zBuffer, w, h, x, y, colorIdx)
    -- Convert to 0‑based indexing because renderer uses 0..w-1, 0..h-1
    x = x - 1
    y = y - 1

    if x < 0 or x >= w or y < 0 or y >= h then return end

    buffer[y][x] = colorIdx
    zBuffer[y][x] = 0
end


-- Draw a single character
local function drawChar(buffer, zBuffer, w, h, ch, x, y, colorIdx, scale)
    scale = scale or 1
    ch = string.upper(ch)
    local glyph = glyphs[ch] or glyphs[" "]

    for col = 1, 6 do
        local byte = glyph[col] or 0
        for row = 0, 7 do
            -- LSB at top: bit row
            if bit32.band(byte, bit32.lshift(1, row)) ~= 0 then
                local px = x + (col - 1) * scale
                local py = y + row * scale
                for sx = 0, scale - 1 do
                    for sy = 0, scale - 1 do
                        plotPixel(buffer, zBuffer, w, h, px + sx, py + sy, colorIdx)
                    end
                end
            end
        end
    end
end

-- Public: draw a string
function text.drawString(buffer, zBuffer, w, h, str, startX, startY, colorIdx, scale, lineHeight)
    lineHeight = lineHeight or (8 * scale + 6)   -- 8px glyph + padding


    scale = scale or 1
    colorIdx = colorIdx or 11
    local x = startX
    local y = startY

    for i = 1, #str do
        local ch = str:sub(i, i)
        drawChar(buffer, zBuffer, w, h, ch, x, y, colorIdx, scale)
        local charSpacing = 0   -- was 1
        x = x + (6 + charSpacing) * scale -- 6px glyph + 1px spacing
    end

    return startY + lineHeight
end

